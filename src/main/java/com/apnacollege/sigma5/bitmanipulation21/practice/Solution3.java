package com.apnacollege.sigma5.bitmanipulation21;

public class Solution3 {
    public static void main(String[] args) {
        int x = 6; 
        System.out.println(x + " x " + 1 + " is " + --x);

        x = -4;
        System.out.println(x + " x " + 1 + " is " + --x);

        x = 0;
        System.out.println(x + " + " + 1 + " is " + --x);
    }
}
